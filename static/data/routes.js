function slicedVariant(source, startIndex, stopIndexes) {
  const coordinates = source.coordinates.slice(startIndex);
  return {
    coordinates,
    stopIndexes: stopIndexes.map(index => index - startIndex),
    meters: Math.round(routeDistanceFromCoordinates(coordinates))
  };
}

function routeDistanceFromCoordinates(coordinates) {
  return coordinates.slice(1).reduce((total, point, index) => {
    const previous = coordinates[index];
    return total + Math.hypot((point[0] - previous[0]) * 111195, (point[1] - previous[1]) * 98650);
  }, 0);
}

